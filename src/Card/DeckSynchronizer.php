<?php

declare(strict_types=1);

namespace MarilenaRM\RecallBundle\Card;

use MarilenaRM\RecallBundle\Fact\Fact;
use MarilenaRM\RecallBundle\Fact\FactExtractorInterface;
use Symfony\AI\Platform\Exception\AuthenticationException;
use Symfony\AI\Platform\Exception\ExceptionInterface;
use Symfony\AI\Platform\Exception\MissingModelSupportException;
use Symfony\AI\Platform\Exception\ModelNotFoundException;
use Symfony\AI\Platform\Exception\RateLimitExceededException;

final readonly class DeckSynchronizer
{
    /**
     * @param iterable<FactExtractorInterface> $extractors
     */
    public function __construct(
        private iterable $extractors,
        private DeckStorage $storage,
        private CardGenerator $generator,
        private DuplicateFinder $duplicateFinder,
    ) {
    }

    public function plan(): SyncReport
    {
        $deck = $this->storage->load();
        $vanished = array_flip($deck->factIds());
        $unchanged = $toGenerate = $obsolete = [];

        foreach ($this->extractors as $extractor) {
            foreach ($extractor->extract() as $fact) {
                unset($vanished[$fact->id]);
                $fingerprint = $deck->fingerprintOf($fact->id);

                if ($fingerprint === $fact->fingerprint) {
                    $unchanged[] = $fact;
                    continue;
                }

                $toGenerate[] = $fact;
                array_push($obsolete, ...$deck->cardsOf($fact->id));
            }
        }

        foreach (array_keys($vanished) as $factId) {
            array_push($obsolete, ...$deck->cardsOf($factId));
        }

        return new SyncReport($unchanged, $toGenerate, array_keys($vanished), $obsolete);
    }

    /**
     * Saves after each fact: an interrupted run keeps the cards already paid for. A fact the model
     * fails on keeps its previous cards and is retried on the next run, without holding back the
     * facts after it; failures that would hit every fact abort the run instead.
     *
     * Deduplication only drops cards generated by this run: a card already in the deck keeps the
     * progress developers made on it.
     *
     * @param \Closure(Fact, list<Card>): void|null $onGenerated
     */
    public function apply(SyncReport $report, ?\Closure $onGenerated = null): SyncResult
    {
        $deck = $this->storage->load();

        foreach ($report->vanished as $factId) {
            $deck->forget($factId);
        }

        // Code moved within its file: same fingerprint, new line number.
        foreach ($report->unchanged as $fact) {
            $deck->relocate($fact);
        }
        $this->storage->save($deck);

        $failures = $generated = [];
        foreach ($report->toGenerate as $fact) {
            try {
                $cards = $this->generator->generate($fact);
            } catch (AuthenticationException|ModelNotFoundException|MissingModelSupportException|RateLimitExceededException $e) {
                throw $e;
            } catch (ExceptionInterface $e) {
                $failures[$fact->id] = $e;
                continue;
            }

            $deck->record($fact, $cards);
            $this->storage->save($deck);
            array_push($generated, ...$cards);

            if (null !== $onGenerated) {
                $onGenerated($fact, $cards);
            }
        }

        $generatedIds = array_map(static fn (Card $card): string => $card->id, $generated);
        $existing = array_values(array_filter($deck->cards(), static fn (Card $card): bool => !\in_array($card->id, $generatedIds, true)));

        try {
            $duplicateIds = $this->duplicateFinder->find($existing, $generated);
        } catch (ExceptionInterface $e) {
            return new SyncResult($failures, [], $e);
        }

        $deck->drop($duplicateIds);
        $this->storage->save($deck);

        return new SyncResult($failures, array_values(array_filter(
            $generated,
            static fn (Card $card): bool => \in_array($card->id, $duplicateIds, true),
        )));
    }
}
